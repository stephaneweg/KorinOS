/* smull + asr 16, 32 bits gardés */
static inline s32 smulw(s32 a, s32 b)
{
	return (s32)(((s64)a * b) >> 16);
}
static inline s32 shl32(s32 v, u32 n)
{
	return (s32)((u32)v << (n & 31));
}
static inline s32 sat16(s32 v)
{
	if (v > 32767)
		v = 32767;
	if (v < -32768)
		v = -32768;
	return v;
}

/* gain (log, Q7) -> linéaire (silk_log2lin) */
static s32 sk_log2lin(s32 x)
{
	if (x < 0)
		return 0;
	if (x >= 3967)
		return 0x7FFFFFFF;
	s32 out = shl32(1, (u32)x >> 7);
	s32 frac = x & 0x7F;
	s32 t = (128 - frac) * frac;
	t = (s32)(((s64)t * -174) >> 16) + frac; /* SMLAWB(frac, ..., -174) */
	if (x < 2048)
		return out + ((out * t) >> 7);
	return out + (out >> 7) * t;
}

/* silk_LSHIFT_SAT32 */
static s32 sk_lsat(s32 v, u32 s)
{
	s32 mn = (s32)0x80000000 >> (s & 31);
	s32 mx = 0x7FFFFFFF >> (s & 31);
	if (v < mn)
		v = mn;
	if (v > mx)
		v = mx;
	return shl32(v, s);
}

static inline s32 sk_absw(s32 v)
{
	return v < 0 ? (s32)(0 - (u32)v) : v;
}

/* b32, Qres -> 2^Qres / b32 approché (silk_INVERSE32_varQ) */
static s32 sk_inv32(s32 b, s32 q)
{
	s32 h = (s32)ak_clz32((u32)sk_absw(b)) - 1; /* b_headrm */
	s32 nrm = shl32(b, (u32)h);
	s32 inv = ak_sdivw(0x1FFFFFFF, nrm >> 16);
	s32 res = shl32(inv, 16);
	s32 err = (s32)(((s64)nrm * (s16)inv) >> 16); /* err = ((1 << 29) - SMULWB(nrm, inv)) << 3 */
	err = shl32(0x20000000 - err, 3);
	res += (s32)(((s64)err * inv) >> 16); /* result += (err inv) >> 16 */
	s32 ls = 61 - h - q;
	if (ls <= 0)
		return sk_lsat(res, (u32)-ls);
	if (ls >= 32)
		return 0;
	return res >> ls;
}

/* a32, b32, Qres -> (a32 << Qres) / b32 approché (silk_DIV32_varQ) */
static s32 sk_div32(s32 a, s32 b, s32 q)
{
	s32 ah = (s32)ak_clz32((u32)sk_absw(a)) - 1;
	s32 an = shl32(a, (u32)ah);
	s32 bh = (s32)ak_clz32((u32)sk_absw(b)) - 1;
	s32 bn = shl32(b, (u32)bh);
	s32 inv = ak_sdivw(0x1FFFFFFF, bn >> 16);
	s16 invs = (s16)inv;
	s32 res = (s32)(((s64)an * invs) >> 16); /* SMULWB(a32_nrm, b32_inv) */
	an -= shl32((s32)(((s64)bn * res) >> 32), 3); /* a32_nrm -= SMMUL(b32_nrm, result) << 3 */
	res += (s32)(((s64)an * invs) >> 16);
	s32 ls = 29 + ah - bh - q;
	if (ls < 0)
		return sk_lsat(res, (u32)-ls);
	if (ls >= 32)
		return 0;
	return res >> ls;
}

