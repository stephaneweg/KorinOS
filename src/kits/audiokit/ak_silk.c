static inline u32 skicdf(struct ec_dec *ec, const u8 *t)
{
	return ec_icdf(ec, t, 8);
}

/* canal, trame dans le paquet, 1 : LBRR, codage : indices de la trame
 * (silk_decode_indices) */
static void sk_indices(struct skc *c, struct ec_dec *ec, u32 fr, u32 lbrr, u32 coding)
{
	/* type de signal, décalage de quantification */
	u32 v;
	if (!lbrr && !c->vad[fr])
		v = skicdf(ec, sk_type_novad);
	else
		v = skicdf(ec, sk_type_vad) + 2;
	c->type = (s32)(v >> 1);
	c->qoff = (s32)(v & 1);
	/* gains */
	if (coding == 2) {
		v = skicdf(ec, sk_dgain);
	} else {
		u32 hi = ec_icdf(ec, sk_gain_icdf + ((u32)c->type << 3), 8) << 3;
		v = skicdf(ec, sk_unif8) + hi;
	}
	c->gidx[0] = (u8)v;
	for (u32 i = 1; i < (u32)c->nbsub; i++)
		c->gidx[i] = (u8)skicdf(ec, sk_dgain);
	/* NLSF : premier étage, puis résidus */
	const u8 *t = c->wb ? sk_cb1i_wb : sk_cb1i_nb;
	v = ec_icdf(ec, t + (((u32)c->type >> 1) << 5), 8);
	c->nlsfidx[0] = (u8)v;
	const u8 *sel = (c->wb ? sk_sel_wb : sk_sel_nb) + ((v * (u32)c->order) >> 1); /* sélection des tables */
	for (u32 i = 0; i < (u32)c->order; i++) {
		u32 e = sel[i >> 1];
		e = i & 1 ? (e >> 5) & 7 : (e >> 1) & 7;
		const u8 *t2 = (c->wb ? sk_cb2i_wb : sk_cb2i_nb) + e * 9;
		u32 r = ec_icdf(ec, t2, 8);
		if (!r)
			r = 0 - skicdf(ec, sk_nlsf_ext);
		else if (r == 8)
			r = skicdf(ec, sk_nlsf_ext) + r;
		c->nlsfidx[1 + i] = (u8)(r - 4);
	}
	/* interpolation */
	v = 4;
	if (c->nbsub == 4)
		v = skicdf(ec, sk_interp);
	c->interp = (s32)v;
	if (c->type == 2) {
		/* hauteur : relative ou absolue */
		u32 abs = 1;
		if (coding == 2 && c->ecptype == 2) {
			u32 dl = skicdf(ec, sk_dlag_icdf);
			if (dl) {
				c->lagidx = (s32)(dl + (u32)c->ecplag - 9);
				abs = 0;
			}
		}
		if (abs) {
			u32 hi = skicdf(ec, sk_lag_icdf) * ((u32)c->fs >> 1);
			c->lagidx = (s32)(ec_icdf(ec, c->lowbits, 8) + hi);
		}
		c->ecplag = c->lagidx;
		c->contidx = (s32)ec_icdf(ec, c->contour, 8);
		c->peridx = (s32)skicdf(ec, sk_per_icdf);
		for (u32 i = 0; i < (u32)c->nbsub; i++) {
			const u8 *g = (u32)c->peridx < 1 ? sk_ltpg0 : c->peridx == 1 ? sk_ltpg1 : sk_ltpg2;
			c->ltpidx[i] = (u8)skicdf(ec, g);
		}
		v = 0;
		if (!coding)
			v = skicdf(ec, sk_ltpscale_icdf);
		c->ltpscidx = (s32)v;
	}
	c->ecptype = c->type;
	c->seed = (s32)skicdf(ec, sk_unif4);
}

/* p, table de coquille -> *a = premier fils, *b = second (decode_split) */
static void sk_split(struct ec_dec *ec, u32 p, const u8 *t, u32 *a, u32 *b)
{
	if (!p) {
		*a = 0;
		*b = 0;
		return;
	}
	u32 x = ec_icdf(ec, t + sk_shell_off[p], 8);
	*a = x;
	*b = p - x;
}

/* sortie (16 x 16 bits), impulsions du bloc : codage en coquille
 * (silk_shell_decoder : 4 niveaux de divisions binaires) */
static void sk_shell(struct ec_dec *ec, s16 *o, u32 n)
{
	u32 p3a, p3b, a, b, c, d, e, f;
	sk_split(ec, n, sk_shell3, &p3a, &p3b);
	u32 p = p3a;
	for (u32 h = 0;; h = 8) {
		sk_split(ec, p, sk_shell2, &a, &b);
		sk_split(ec, a, sk_shell1, &c, &d);
		sk_split(ec, c, sk_shell0, &e, &f);
		o[h] = (s16)e;
		o[h + 1] = (s16)f;
		sk_split(ec, d, sk_shell0, &e, &f);
		o[h + 2] = (s16)e;
		o[h + 3] = (s16)f;
		sk_split(ec, b, sk_shell1, &c, &d);
		sk_split(ec, c, sk_shell0, &e, &f);
		o[h + 4] = (s16)e;
		o[h + 5] = (s16)f;
		sk_split(ec, d, sk_shell0, &e, &f);
		o[h + 6] = (s16)e;
		o[h + 7] = (s16)f;
		if (h)
			break;
		p = p3b;
	}
}

/* impulsions (16 bits), type de signal, décalage, échantillons (silk_decode_pulses) */
static void sk_pulses(struct ec_dec *ec, s16 *q, u32 type, u32 qoff, u32 len)
{
	u32 sums[20], nlsb[20];
	u32 rate = ec_icdf(ec, sk_rate + (type >> 1) * 9, 8); /* niveau de débit */
	u32 nb = len >> 4; /* blocs de 16 */
	if ((nb << 4) < len)
		nb++;
	for (u32 i = 0; i < nb; i++) {
		u32 l = 0; /* bits faibles */
		u32 s = ec_icdf(ec, sk_ppb + 18 * rate, 8);
		while (s == 17) {
			l++;
			s = ec_icdf(ec, sk_ppb + 9 * 18 + (l == 10), 8);
		}
		sums[i] = s;
		nlsb[i] = l;
	}
	for (u32 i = 0; i < nb; i++) { /* coquilles */
		if (sums[i])
			sk_shell(ec, q + i * 16, sums[i]);
		else
			memset(q + i * 16, 0, 32);
	}
	for (u32 i = 0; i < nb; i++) { /* bits faibles */
		u32 l = nlsb[i];
		if (!l)
			continue;
		for (u32 k = 0; k < 16; k++) {
			s32 v = q[i * 16 + k];
			for (u32 j = 0; j < l; j++)
				v = (s32)skicdf(ec, sk_lsb) + shl32(v, 1);
			q[i * 16 + k] = (s16)v;
		}
		sums[i] |= l << 5;
	}
	/* signes */
	u32 base = (qoff + (type << 1)) * 7; /* 7 (décalage + 2 type) */
	u32 nb2 = (len + 8) >> 4;
	for (u32 i = 0; i < nb2; i++) {
		u32 s = sums[i];
		if (!s)
			continue;
		u32 p = s & 31;
		if (!(p < 6))
			p = 6;
		u8 icdf[2] = {sk_sign[p + base], 0};
		for (u32 j = 0; j < 16; j++) {
			s32 v = q[i * 16 + j];
			if (v <= 0)
				continue;
			s32 b = (s32)ec_icdf(ec, icdf, 8);
			v = v * ((b << 1) - 1);
			q[i * 16 + j] = (s16)v;
		}
	}
}

