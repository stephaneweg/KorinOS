/* rééchantillonneur, fréquence d'entrée (kHz) */
static void sk_rsinit(struct skrs *rs, u32 khz)
{
	memset(rs, 0, RS_SIZE);
	rs->fsin = (s32)khz;
	s32 dl = 0; /* retard (8, 12, 16 kHz -> 48 kHz) */
	if (khz == 12)
		dl = 4;
	if (khz == 16)
		dl = 7;
	rs->delay = dl;
	rs->batch = (s32)(10 * khz);
	u32 fin = khz * 1000;
	u32 inv = ((fin << 15) / 48000) << 2; /* invRatio_Q16 */
	u32 lim = fin << 1;
	while ((s32)(((s64)(s32)inv * 48000) >> 16) < (s32)lim)
		inv++;
	rs->inv = (s32)inv;
}

