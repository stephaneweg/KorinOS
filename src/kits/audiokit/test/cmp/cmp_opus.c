#define ECB 112
/* état du décodeur de plage, pointeurs rendus relatifs aux données */
static void ec_snap(long *o, const uint8_t *ec, const uint8_t *buf)
{
	uint64_t v[14];
	memcpy(v, ec, ECB);
	for (int i = 0; i < 4; i++)
		v[i] -= (uint64_t)buf;
	memcpy(o, v, ECB);
}

static void t_ec(int ref)
{
	static uint8_t buf[400];
	static long res[200 * 20];
	char nm[64];
	for (int t = 0; t < 120; t++) {
		rng = 1000 + t;
		int n = t < 6 ? t : (int)(rnd() % 320);
		for (int i = 0; i < n; i++) {
			uint32_t r = rnd();
			buf[i] = t % 9 == 1 ? 0 : t % 9 == 2 ? 0xFF : (uint8_t)r;
		}
		uint8_t *ec = ak_alloc(ECB);
		memset(ec, 0xA5, ECB);
		AKCALL(ref, ec_init, ec, buf, n);
		if (t % 7 == 3 && n > 4)
			AKCALL(ref, ec_shrink, ec, rnd() % 4);
		int k = 0;
		ec_snap(res + k, ec, buf);
		k += 14;
		int nops = 40 + t % 50;
		for (int j = 0; j < nops; j++) {
			uint32_t op = rnd() % 11;
			long a = 0, b = 0;
			if (op == 0) { /* ec_decode + ec_update */
				uint32_t ft = 2 + rnd() % (j & 1 ? 65000 : 40);
				a = (uint32_t)AKCALL(ref, ec_decode, ec, ft);
				uint32_t s = (uint32_t)a, fl = s, fh = s + 1;
				if (rnd() % 3 == 0 && fl)
					fl -= 1;
				if (rnd() % 3 == 0 && fh < ft)
					fh += 1;
				AKCALL(ref, ec_update, ec, fl, fh, ft);
			} else if (op == 1) { /* ec_decode_bin + ec_update */
				uint32_t bits = 1 + rnd() % 15;
				a = (uint32_t)AKCALL(ref, ec_decode_bin, ec, bits);
				AKCALL(ref, ec_update, ec, a, a + 1, 1u << bits);
			} else if (op == 2) {
				a = (uint32_t)AKCALL(ref, ec_bit_logp, ec, 1 + rnd() % 15);
			} else if (op == 3 || op == 4) { /* tables icdf */
				uint32_t ftb = op == 3 ? (j % 3 ? 8 : 1 + rnd() % 8) : 15;
				uint32_t top = 1u << ftb, m = 2 + rnd() % 14;
				uint8_t t8[20];
				uint16_t t16[20];
				uint32_t v = top;
				for (uint32_t i = 0; i < m; i++) {
					uint32_t left = m - i;
					uint32_t step = 1 + rnd() % (v > left ? v - left + 1 : 1);
					if (step > v - (left - 1))
						step = v - (left - 1);
					v -= step;
					if (i == m - 1)
						v = 0;
					t8[i] = (uint8_t)(v > 255 ? 255 : v);
					t16[i] = (uint16_t)v;
				}
				if (op == 3)
					a = (uint32_t)AKCALL(ref, ec_icdf, ec, t8, ftb);
				else
					a = (uint32_t)AKCALL(ref, ec_icdf16, ec, t16, ftb);
			} else if (op == 5) {
				a = (uint32_t)AKCALL(ref, ec_bits, ec, rnd() % 26);
			} else if (op == 6) {
				uint32_t ft = rnd() % 4 == 0 ? 2 + rnd() % 254 : (rnd() << 8) | (rnd() & 255);
				if (ft < 2)
					ft = 2;
				a = (uint32_t)AKCALL(ref, ec_uint, ec, ft);
			} else if (op == 7) {
				a = AKCALL(ref, ec_tell, ec);
				b = AKCALL(ref, ec_tell_frac, ec);
			} else if (op == 8) {
				uint32_t fs = 64 + rnd() % 30000, dec = rnd() % 16384;
				if (j % 5 == 0)
					fs = 32768 - 64 + rnd() % 33;
				a = (int)AKCALL(ref, ec_laplace, ec, fs, dec);
			} else if (op == 9) {
				AKCALL(ref, ec_norm, ec);
			} else {
				a = (uint32_t)AKCALL(ref, ec_uint, ec, 2 + rnd() % 300);
			}
			res[k++] = (long)op << 32 | (uint32_t)j;
			res[k++] = a;
			res[k++] = b;
			ec_snap(res + k, ec, buf);
			k += 14;
		}
		snprintf(nm, sizeof nm, "ec%d.n%d", t, n);
		OUT(nm, res, k * sizeof(long));
		ak_free(ec);
	}
}

