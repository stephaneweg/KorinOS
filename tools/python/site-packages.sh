#!/bin/sh
# site-packages : les paquets de Python prepares sur le PC (voie A de docs/PYTHON.md §2.8), poses
# dans build/python/sdroot/python/lib/python3.14/site-packages (recopie sur la carte par build.ps1).
# A lancer dans WSL depuis la racine du depot, apres sh tools/python/build.sh (qui vide sdroot) :
#     sh tools/python/site-packages.sh
#
# Les modules C (tree-sitter, tree-sitter-bash, cffi) sont construits par build-ext.sh en .so ;
# les paquets purs viennent de PyPI en roues none-any. pip installe pour la carte, pas pour le PC :
# --platform linux_aarch64, cp314 ; --find-links prend nos roues avant PyPI. Les .pyc sont faits
# ici en « checked-hash » : la date de FAT (2 s) ne les invalide pas, une modification du .py si.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
WORK=${WORK:-$HOME/.cache/armpi-python}
OUT=${OUT:-$ROOT/build/python}
BUILD_PYTHON=${BUILD_PYTHON:-/usr/bin/python3.14}
T=$ROOT/tools/python
W=$OUT/wheels
SP=$OUT/site-packages

# les paquets en C, pour Korin (tree-sitter : son endian.h ne connait que __linux__ et les BSD ;
# le contournement d'un defaut de l'optimiseur de GCC sur aarch64, que son setup.py ne pose que
# si la machine qui construit est aarch64)
rm -rf "$W"
EXT_CFLAGS="-DHAVE_ENDIAN_H --param=early-inlining-insns=9" sh "$T/build-ext.sh" tree-sitter==0.26.0
sh "$T/build-ext.sh" tree-sitter-bash==0.25.1 cffi==2.0.0

# l'arbre : nos roues et les paquets purs (pip, setuptools pour compiler sur la carte, pycparser
# pour cffi)
rm -rf "$SP"
"$WORK/venv-ext/bin/python" -m pip install --disable-pip-version-check --no-cache-dir -q \
	--target "$SP" --no-compile --platform linux_aarch64 --implementation cp --python-version 3.14 \
	--abi cp314 --only-binary=:all: --find-links "$W" \
	pip==26.3 setuptools==80.9.0 pycparser==2.23 \
	cffi==2.0.0 tree-sitter==0.26.0 tree-sitter-bash==0.25.1
rm -rf "$SP/bin"		# (les lanceurs de pip : #! vers le Python du PC ; sur la carte : python3 -m pip)
"$BUILD_PYTHON" -I -m compileall -q -j0 --invalidation-mode checked-hash "$SP" >/dev/null

D=$OUT/sdroot/python/lib/python3.14/site-packages
[ -d "$OUT/sdroot/python" ] || { echo "sdroot absent : sh tools/python/build.sh" >&2; exit 1; }
rm -rf "$D" && cp -r "$SP" "$D"
# pip.conf du site (sys.prefix) : HOME vaut SD0:/ sous Korin, un chemin a volume que pip refuse pour son
# cache (os.path.isabs) ; le cache dans /python, chemin virtuel ; uid 0 est le seul utilisateur
mkdir -p "$OUT/sdroot/python/cache"
cat > "$OUT/sdroot/python/pip.conf" <<EOF
[global]
cache-dir = /python/cache/pip
disable-pip-version-check = true
root-user-action = ignore
EOF
ls "$D"
du -sh "$D"
