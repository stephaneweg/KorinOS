#!/bin/sh
# site-packages : les paquets de Python prepares sur le PC (voie A de docs/PYTHON.md §2.8), poses
# dans build/python/sdroot/python/lib/python3.14/site-packages (recopie sur la carte par build.ps1).
# A lancer dans WSL depuis la racine du depot, apres sh tools/python/build.sh (qui vide sdroot) :
#     sh tools/python/site-packages.sh
#
# Les modules C (tree-sitter, tree-sitter-bash, cffi) sont construits par build-ext.sh en .so, les
# modules Rust (pydantic-core, rpds-py, cryptography) par build-rust-ext.sh ;
# les paquets purs viennent de PyPI en roues none-any. pip installe pour la carte, pas pour le PC :
# --platform linux_aarch64, cp314 ; --find-links prend nos roues avant PyPI. Les .pyc sont faits
# ici en « checked-hash » : la date de FAT (2 s) ne les invalide pas, une modification du .py si.
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
WORK=${WORK:-$HOME/.cache/armpi-python}
OUT=${OUT:-$ROOT/build/python}
BUILD_PYTHON=${BUILD_PYTHON:-/usr/bin/python3.14}
T=$ROOT/tools/python
W=$OUT/wheels
SP=$OUT/site-packages

# les paquets en C, pour Korin (tree-sitter : son endian.h ne connait que __linux__ et les BSD ;
# le contournement d'un defaut de l'optimiseur de GCC sur aarch64, que son setup.py ne pose que
# si la machine qui construit est aarch64)
rm -rf "$W"
EXT_CFLAGS="-DHAVE_ENDIAN_H --param=early-inlining-insns=9" sh "$T/build-ext.sh" tree-sitter==0.26.0
sh "$T/build-ext.sh" tree-sitter-bash==0.25.1 cffi==2.0.0
# les modules Rust (etape 5, docs/PYTHON-PORT.md) : une cdylib par paquet, versions de Vibe 3.1.2
bash "$T/build-rust-ext.sh" pydantic-core==2.46.4 rpds-py==0.30.0 cryptography==50.0.0
# le module d'essai qui panique (tools/python/tests/step5.py) : sur la carte d'essai seulement
rm -rf "$OUT/tests/wheels" "$OUT/tests/site-packages"
OUT_WHEELS=$OUT/tests/wheels bash "$T/build-rust-ext.sh" "$T/tests/panic"
"$BUILD_PYTHON" -I -m zipfile -e "$OUT"/tests/wheels/korin_panic_probe-*.whl "$OUT/tests/site-packages"
# pytest et ce que demandent les suites de pydantic-core, rpds-py et cryptography (paquets purs),
# et leurs dossiers tests (des sdist), pour la carte d'essai seulement
"$WORK/venv-ext/bin/python" -m pip install --disable-pip-version-check --no-cache-dir -q 	--target "$OUT/tests/site-packages" --no-compile --platform linux_aarch64 --implementation cp 	--python-version 3.14 --abi cp314 --only-binary=:all: --no-deps 	pytest==9.2.0 iniconfig==2.3.1 pluggy==1.7.0 packaging==26.3 pygments==2.21.0 	hypothesis==6.155.7 sortedcontainers==2.4.0 dirty-equals==0.11 pytest-mock==3.17.0 	pytest-timeout==2.4.0 inline-snapshot==0.36.2 asttokens==3.0.2 executing==2.3.0 rich==15.0.0 	markdown-it-py==4.3.0 mdurl==0.1.2 pretend==1.0.9 cryptography-vectors==50.0.0 certifi==2026.10.23
rm -rf "$OUT/tests/site-packages/bin"
RX=$WORK/rust-ext/src
rm -rf "$OUT/tests/rust-ext" && mkdir -p "$OUT/tests/rust-ext"
for d in pydantic_core-2.46.4 rpds_py-0.30.0 cryptography-50.0.0; do
	mkdir -p "$OUT/tests/rust-ext/$d"
	cp -r "$RX/$d/tests" "$RX/$d/pyproject.toml" "$OUT/tests/rust-ext/$d/"
done

# l'arbre : nos roues et les paquets purs (pip, setuptools pour compiler sur la carte, pycparser
# pour cffi)
rm -rf "$SP"
"$WORK/venv-ext/bin/python" -m pip install --disable-pip-version-check --no-cache-dir -q \
	--target "$SP" --no-compile --platform linux_aarch64 --implementation cp --python-version 3.14 \
	--abi cp314 --only-binary=:all: --find-links "$W" \
	pip==26.3 setuptools==80.9.0 pycparser==2.23 \
	cffi==2.0.0 tree-sitter==0.26.0 tree-sitter-bash==0.25.1 	pydantic-core==2.46.4 pydantic==2.13.4 annotated-types==0.7.0 typing-extensions==4.16.0 	typing-inspection==0.4.2 rpds-py==0.30.0 referencing==0.37.0 attrs==26.1.0 	jsonschema==4.26.0 jsonschema-specifications==2025.9.1 cryptography==50.0.0 joserfc==1.7.7
rm -rf "$SP/bin"		# (les lanceurs de pip : #! vers le Python du PC ; sur la carte : python3 -m pip)
"$BUILD_PYTHON" -I -m compileall -q -j0 --invalidation-mode checked-hash "$SP" >/dev/null

D=$OUT/sdroot/python/lib/python3.14/site-packages
[ -d "$OUT/sdroot/python" ] || { echo "sdroot absent : sh tools/python/build.sh" >&2; exit 1; }
rm -rf "$D" && cp -r "$SP" "$D"
# pip.conf du site (sys.prefix) : HOME vaut SD0:/ sous Korin, un chemin a volume que pip refuse pour son
# cache (os.path.isabs) ; le cache dans /python, chemin virtuel ; uid 0 est le seul utilisateur
mkdir -p "$OUT/sdroot/python/cache"
cat > "$OUT/sdroot/python/pip.conf" <<EOF
[global]
cache-dir = /python/cache/pip
disable-pip-version-check = true
root-user-action = ignore
EOF
ls "$D"
du -sh "$D"
