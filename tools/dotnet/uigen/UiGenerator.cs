// UiGenerator.cs -- les .ui compiles : un generateur source de Roslyn, charge dans csc par pibuild
// (-analyzer, -additionalfile, docs/DOTNET.md). MainForm.ui donne une partie de la classe MainForm : ses
// champs (Name) et InitializeComponent, en C# ordinaire, sans XML a l'execution. Le controle racine dit la
// classe de base. Une erreur du .ui (controle, propriete, valeur, methode inconnus) sort de csc a sa ligne.
#nullable disable
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Armpi.UiGen;

[Generator (LanguageNames.CSharp)]
public sealed class UiGenerator : IIncrementalGenerator
{
	static DiagnosticDescriptor Rule (string id, string text) =>
		new DiagnosticDescriptor (id, ".ui", text, ".ui", DiagnosticSeverity.Error, true);
	static readonly DiagnosticDescriptor Xml = Rule ("UI0001", "{0}");
	static readonly DiagnosticDescriptor Control = Rule ("UI0002", "controle inconnu : {0}");
	static readonly DiagnosticDescriptor Member = Rule ("UI0003", "{0} n'a ni propriete ni evenement {1}");
	static readonly DiagnosticDescriptor Value = Rule ("UI0004", "{0} : valeur refusee : {1}");
	static readonly DiagnosticDescriptor Handler = Rule ("UI0005", "methode inconnue dans {0} : {1}");
	static readonly DiagnosticDescriptor Child = Rule ("UI0006", "{0} ne prend pas {1}");

	public void Initialize (IncrementalGeneratorInitializationContext context)
	{
		var files = context.AdditionalTextsProvider
			.Where (f => f.Path.EndsWith (".ui", StringComparison.OrdinalIgnoreCase))
			.Select ((f, ct) => (f.Path, Text: f.GetText (ct)?.ToString ()));
		context.RegisterSourceOutput (files.Collect ().Combine (context.CompilationProvider), (spc, all) =>
		{
			foreach (var f in all.Left)
				new Unit (spc, all.Right, f.Path, f.Text).Run ();
		});
	}

	sealed class Unit
	{
		readonly SourceProductionContext _ctx;
		readonly Compilation _comp;
		readonly string _path, _text, _class;
		readonly StringBuilder _fields = new (), _code = new ();
		readonly INamedTypeSymbol _user;
		int _next;

		internal Unit (SourceProductionContext ctx, Compilation comp, string path, string text)
		{
			_ctx = ctx; _comp = comp; _path = path; _text = text;
			_class = Path.GetFileNameWithoutExtension (path);
			_user = comp.GetSymbolsWithName (_class, SymbolFilter.Type).OfType<INamedTypeSymbol> ().FirstOrDefault ();
		}

		void Fail (DiagnosticDescriptor d, IXmlLineInfo at, params object[] args)
		{
			var p = at != null && at.HasLineInfo () ? new LinePosition (at.LineNumber - 1, Math.Max (at.LinePosition - 1, 0)) : default;
			_ctx.ReportDiagnostic (Diagnostic.Create (d, Location.Create (_path, default, new LinePositionSpan (p, p)), args));
		}

		INamedTypeSymbol FindControl (string name) =>
			_comp.GetTypeByMetadataName ("System.Windows.Forms." + name)
			?? _comp.GetTypeByMetadataName ("System.Windows.Media.Media3D." + name)
			?? _comp.GetSymbolsWithName (name, SymbolFilter.Type).OfType<INamedTypeSymbol> ().FirstOrDefault ();

		static string Full (ITypeSymbol t) => t.ToDisplayString (SymbolDisplayFormat.FullyQualifiedFormat);
		static string Text (string s) => SymbolDisplay.FormatLiteral (s, true);

		static IEnumerable<ISymbol> Members (ITypeSymbol t, string name)
		{
			for (; t != null; t = t.BaseType)
				foreach (var m in t.GetMembers (name))
					yield return m;
		}

		internal void Run ()
		{
			XElement root;
			try { root = XDocument.Parse (_text ?? "", LoadOptions.SetLineInfo).Root; }
			catch (XmlException e)
			{
				var p = new LinePosition (Math.Max (e.LineNumber - 1, 0), Math.Max (e.LinePosition - 1, 0));
				_ctx.ReportDiagnostic (Diagnostic.Create (Xml, Location.Create (_path, default, new LinePositionSpan (p, p)), e.Message));
				return;
			}
			var type = FindControl (root.Name.LocalName);
			if (type == null)
			{
				Fail (Control, root, root.Name.LocalName);
				return;
			}
			Apply ("this", type, root, _user ?? type);
			var ns = _user != null && !_user.ContainingNamespace.IsGlobalNamespace ? _user.ContainingNamespace.ToDisplayString () : null;
			var o = new StringBuilder ("// <auto-generated/> depuis " + Path.GetFileName (_path) + "\n#nullable disable\n");
			if (ns != null)
				o.Append ("namespace ").Append (ns).Append (";\n");
			o.Append ("partial class ").Append (_class).Append (" : ").Append (Full (type)).Append ("\n{\n");
			o.Append (_fields);
			if (_user == null || _user.InstanceConstructors.All (c => c.IsImplicitlyDeclared))
				o.Append ("\tpublic ").Append (_class).Append (" () { InitializeComponent (); }\n");
			o.Append ("\tvoid InitializeComponent ()\n\t{\n").Append (_code).Append ("\t}\n}\n");
			_ctx.AddSource (_class + ".ui.g.cs", SourceText.From (o.ToString (), Encoding.UTF8));
		}

		string Build (XElement e, ITypeSymbol code)
		{
			string name = e.Name.LocalName;
			if (name == "Include")
				name = Path.GetFileNameWithoutExtension ((string) e.Attribute ("Source") ?? "");
			var t = FindControl (name);
			if (t == null)
			{
				Fail (Control, e, name);
				return null;
			}
			string v = "c" + _next++;
			_code.Append ("\t\tvar ").Append (v).Append (" = new ").Append (Full (t)).Append (" ();\n");
			if (e.Name.LocalName != "Include")
				Apply (v, t, e, code);
			return v;
		}

		void Apply (string v, ITypeSymbol t, XElement e, ITypeSymbol code)
		{
			foreach (var a in e.Attributes ())
				Set (v, t, a, code);
			foreach (var child in e.Elements ())
				Child_ (v, t, child, code);
		}

		bool Is (ITypeSymbol t, string name)
		{
			for (; t != null; t = t.BaseType)
				if (t.Name == name)
					return true;
			return false;
		}

		void Child_ (string v, ITypeSymbol t, XElement c, ITypeSymbol code)
		{
			string tag = c.Name.LocalName;
			if (tag == "MenuStrip" && Is (t, "Form"))
			{
				string b = Build (c, code);
				if (b != null)
					_code.Append ("\t\t").Append (v).Append (".MainMenuStrip = ").Append (b).Append (";\n");
			}
			else if (tag == "ToolStripMenuItem" && (Is (t, "MenuStrip") || Is (t, "ToolStripMenuItem")))
			{
				string b = Build (c, code);
				if (b != null)
					_code.Append ("\t\t").Append (v).Append (Is (t, "MenuStrip") ? ".Items" : ".DropDownItems").Append (".Add (").Append (b).Append (");\n");
			}
			else if (tag == "ToolStripSeparator" && Is (t, "ToolStripMenuItem"))
				_code.Append ("\t\t").Append (v).Append (".DropDownItems.Add (\"-\");\n");
			else if (tag == "Item" && Is (t, "ListControl"))
				_code.Append ("\t\t").Append (v).Append (".Items.Add (").Append (Text (c.Value)).Append (");\n");
			else if (tag == "Column" && Is (t, "ListView"))
				_code.Append ("\t\t").Append (v).Append (".Columns.Add (new System.Windows.Forms.ColumnHeader { Text = ")
					.Append (Text ((string) c.Attribute ("Text") ?? "")).Append (", Width = ").Append ((int?) c.Attribute ("Width") ?? 100).Append (" });\n");
			else if (tag == "Column" && Is (t, "DataGridView"))
				_code.Append ("\t\t").Append (v).Append (".Columns.Add (new System.Windows.Forms.DataGridViewColumn (")
					.Append (Text ((string) c.Attribute ("HeaderText") ?? "")).Append (", ").Append ((int?) c.Attribute ("Width") ?? 100).Append ("));\n");
			else if (tag == "Row" && Is (t, "DataGridView"))
				_code.Append ("\t\t").Append (v).Append (".Rows.Add (new object[] { ")
					.Append (string.Join (", ", c.Value.Split ('|').Select (Text))).Append (" });\n");
			else if (tag == "Node" && Is (t, "TreeView"))
				Node (v + ".Nodes", c);
			else if ((tag == "Panel1" || tag == "Panel2") && Is (t, "SplitContainer"))
			{
				var p = Members (t, tag).OfType<IPropertySymbol> ().First ().Type;
				Apply (v + "." + tag, p, c, code);
			}
			else if (Is (t, "Control"))
			{
				string b = Build (c, code);
				if (b != null)
					_code.Append ("\t\t").Append (v).Append (".Controls.Add (").Append (b).Append (");\n");
			}
			else
				Fail (Child, c, t.Name, tag);
		}

		void Node (string into, XElement e)
		{
			string n = "c" + _next++;
			_code.Append ("\t\tvar ").Append (n).Append (" = ").Append (into).Append (".Add (").Append (Text ((string) e.Attribute ("Text") ?? "")).Append (");\n");
			foreach (var c in e.Elements ("Node"))
				Node (n + ".Nodes", c);
		}

		void Set (string v, ITypeSymbol t, XAttribute a, ITypeSymbol code)
		{
			string name = a.Name.LocalName;
			var m = Members (t, name).FirstOrDefault (s => s is IPropertySymbol || s is IEventSymbol);
			if (m is IEventSymbol)
			{
				if (code != null && !Members (code, a.Value).OfType<IMethodSymbol> ().Any ())
					Fail (Handler, a, code.Name, a.Value);
				_code.Append ("\t\t").Append (v).Append ('.').Append (name).Append (" += ").Append (a.Value).Append (";\n");
				return;
			}
			if (m is not IPropertySymbol p)
			{
				Fail (Member, a, t.Name, name);
				return;
			}
			string value = Literal (p.Type, a.Value);
			if (value == null)
			{
				Fail (Value, a, name, a.Value);
				return;
			}
			_code.Append ("\t\t").Append (v).Append ('.').Append (name).Append (" = ").Append (value).Append (";\n");
			if (name == "Name" && a.Value.Length > 0 && v != "this")
			{
				_fields.Append ("\t").Append (Full (t)).Append (' ').Append (a.Value).Append (";\n");
				_code.Append ("\t\t").Append (a.Value).Append (" = ").Append (v).Append (";\n");
			}
		}

		static string Literal (ITypeSymbol t, string s)
		{
			if (t.SpecialType == SpecialType.System_String)
				return Text (s);
			if (t.SpecialType == SpecialType.System_Boolean)
				return bool.TryParse (s, out bool b) ? (b ? "true" : "false") : null;
			if (t.SpecialType == SpecialType.System_Int32)
				return int.TryParse (s, NumberStyles.Integer, CultureInfo.InvariantCulture, out int i) ? i.ToString (CultureInfo.InvariantCulture) : null;
			if (t.TypeKind == TypeKind.Enum)
			{
				var names = s.Split ('|').Select (x => x.Trim ()).ToArray ();
				if (names.Any (n => !t.GetMembers (n).OfType<IFieldSymbol> ().Any ()))
					return null;
				return string.Join (" | ", names.Select (n => Full (t) + "." + n));
			}
			if (t.Name == "Padding")
				return int.TryParse (s, NumberStyles.Integer, CultureInfo.InvariantCulture, out int all) ? "new " + Full (t) + " (" + all + ")" : null;
			if (t.Name == "Point" || t.Name == "Size")
			{
				var v = s.Split (',');
				if (v.Length != 2 || !int.TryParse (v[0].Trim (), out int x) || !int.TryParse (v[1].Trim (), out int y))
					return null;
				return "new " + Full (t) + " (" + x + ", " + y + ")";
			}
			return null;
		}
	}
}
