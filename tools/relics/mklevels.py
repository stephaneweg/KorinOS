def write():
	out = []
	out.append("/*\n * levels.h -- les quinze niveaux de Relics (cinq mondes de trois), une ligne de texte par rangee de cases de"
		   "\n * 20 points. GENERE par tools/relics/mklevels.py : changer le script, pas ce fichier. Inclus par main.c.\n *\n"
		   " *   ' ' le ciel (le decor du fond)      '.' le mur du fond          '#' la roche      '=' la brique\n"
		   " *   '-' une planche (on passe dessous)   'H' une echelle             '^' 'v' des pointes (sol, plafond)\n"
		   " *   'B' un mur fissure (la dynamite)     'C' un sol qui s'effondre   '~' l'eau, les sables, la lave\n"
		   " *   'D' une porte (une cle)              'i' une torche              'w' un ornement du monde\n"
		   " *   't' un piege a pointes cache          'f' un jet de feu           '<' '>' un lanceur de flechettes\n"
		   " *   'P' le depart   'E' la sortie   '+' un point de passage\n"
		   " *   '$' un tresor   '*' la relique  'a' des balles  'd' de la dynamite  'k' une cle  '1' une vie\n"
		   " *   'g' un gardien  's' un tireur   'b' une chauve-souris   'p' une araignee\n"
		   " *   'o' un rocher qui roule   '!' une stalactite   'M' un pilon\n */\n\n")
	out.append("struct level { int world; const char *name; const char *map; };\n\nstatic const struct level levels[] = {\n")
	for world, name, f in LEVELS:
		c = f()
		rows = c.rows()
		for r in rows:
			assert len(r) == c.w
		out.append('\t{ %d, "%s",\n' % (world, name.replace('"', '\\"')))
		for i, r in enumerate(rows):
			out.append('\t  "%s\\n"%s\n' % (r.replace("\\", "\\\\").replace('"', '\\"'), " }," if i == len(rows) - 1 else ""))
	out.append("};\n")
	with open(OUT, "w", encoding="utf-8", newline="\n") as h:
		h.write("".join(out))
	print("levels.h : %d niveaux" % len(LEVELS))


