#!/usr/bin/env python3
# tools/relics/mklevels.py -- les quinze niveaux de Relics (src/apps/relics/levels.h), dessines ici sur une grille de
# cases avec quelques outils (salles, echelles, fosses), puis ecrits en texte dans levels.h. Le jeu ne lit rien : les
# niveaux sont dans le programme. Apres un changement : ce script, puis le parcours de tools/relics/run.sh check,
# qui dit si la sortie de chaque niveau est atteignable par la vraie physique de l'explorateur.
#
#   python3 tools/relics/mklevels.py            -> src/apps/relics/levels.h
#
# La physique (main.c) : un saut monte de 58 points (une marche de 2 cases, pas 3), franchit 3 cases de vide ou de
# pointes ; un saut entier demande 4 cases libres au-dessus du sol. La legende des cases est en tete de levels.h.
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "apps", "relics", "levels.h")


class C:
	"""Une grille de cases, pleine au depart."""

	def __init__(s, w, h, fill="#"):
		s.w, s.h, s.fill = w, h, fill
		s.g = [[fill] * w for _ in range(h)]

	def grow(s, w, h, fill=None):
		"""Plus grande (a droite, en bas), pleine."""
		fill = fill or s.fill
		for r in s.g:
			r += [fill] * (w - s.w)
		s.g += [[fill] * w for _ in range(h - s.h)]
		s.w, s.h = w, h

	def rect(s, x0, y0, x1, y1, ch):
		for y in range(max(0, y0), min(s.h, y1 + 1)):
			for x in range(max(0, x0), min(s.w, x1 + 1)):
				s.g[y][x] = ch

	def room(s, x0, x1, top, floor, ch="."):
		"""Une salle : rangees top .. floor-1 (le sol, la rangee floor, reste plein)."""
		s.rect(x0, top, x1, floor - 1, ch)

	def row(s, x0, x1, y, ch):
		s.rect(x0, y, x1, y, ch)

	def col(s, x, y0, y1, ch):
		s.rect(x, y0, x, y1, ch)

	def lad(s, x, top, bottom):
		"""Une echelle : sa case du haut est dans le sol d'en haut (on s'y tient)."""
		s.col(x, top, bottom, "H")

	def put(s, x, y, text):
		for i, ch in enumerate(text):
			if 0 <= x + i < s.w and 0 <= y < s.h and ch != "_":
				s.g[y][x + i] = ch

	def at(s, x, y, *items):
		"""Des objets, un par case, a partir de (x, y)."""
		for i, ch in enumerate(items):
			s.put(x + i, y, ch)

	def fern(s, x, y):
		"""Une fougere de premier plan, sur une case vide posee sur du plein (sinon, rien)."""
		if s.g[y][x] in " ." and s.g[y + 1][x] in "#=":
			s.g[y][x] = "F"

	def rows(s):
		return ["".join(r) for r in s.g]


def escape(c, x, up, d=1, run=14, pit=2):
	"""La fuite devant le rocher, comme dans le jeu d'origine. Le sol ou l'on marche (la rangee up) finit par un trou
	en colonne x, contre un mur ; on tombe dans un couloir de 2 cases de haut, ou l'on ne peut pas sauter, et le
	rocher, au repos 3 cases derriere, part aussitot. Il faut courir (d : 1 vers la droite, -1 vers la gauche) sur run
	cases, sauter une fosse a pointes de pit cases (le plafond s'ouvre au-dessus) ou le rocher tombe et s'ecrase, et la sortie
	est au bout. La grille doit avoir la place (C.grow) : 5 + 4 rangees sous up, run + pit + 11 colonnes."""
	f = up + 5						# le sol du couloir (rangees f-2, f-1)

	def cols(a, b):						# les colonnes x + a*d .. x + b*d
		return min(x + a * d, x + b * d), max(x + a * d, x + b * d)
	c.rect(x + d, up - 4, x + d, up, c.g[up + 1][x])	# le mur : on ne saute pas le trou
	c.rect(x, up + 1, x, f - 3, ".")			# le trou
	a, b = cols(-4, run)
	c.rect(a, f - 2, b, f - 1, ".")				# le couloir
	a, b = cols(-4, -3)
	c.put(a, f - 1, "o")
	a, b = cols(run - 3, run + pit + 1)
	c.rect(a, f - 5, b, f - 1, ".")				# le plafond s'ouvre : on peut sauter
	a, b = cols(run + 1, run + pit)
	c.rect(a, f, b, f + 2, ".")				# la fosse
	c.row(a, b, f + 3, "^")
	a, b = cols(run + pit + 1, run + pit + 10)
	c.rect(a, f - 4, b, f - 1, ".")				# la salle de la sortie
	c.put(x + (run + pit + 4) * d, f - 3, "i")
	c.put(x + (run + pit + 7) * d, f - 1, "E")


LEVELS = []


def level(world, name):
	def deco(f):
		LEVELS.append((world, name, f))
		return f
	return deco


